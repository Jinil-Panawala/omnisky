import type { SatelliteEntity } from "./types";

function makeSat(
  noradId: number,
  name: string,
  tleLine1: string,
  tleLine2: string,
  category: string,
  classification: string,
  riskScore: number,
  lat: number,
  lon: number
): SatelliteEntity {
  return {
    id: String(noradId),
    type: "satellite",
    noradId,
    name,
    lat,
    lon,
    tleLine1,
    tleLine2,
    category,
    classification,
    riskScore,
    updatedAt: new Date(),
  };
}

