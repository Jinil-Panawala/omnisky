import type { ShipEntity } from "./types";

function makeShip(
  mmsi: string,
  shipName: string,
  lat: number,
  lon: number,
  speedKn: number | null,
  courseDeg: number,
  headingDeg: number,
  shipType: string,
  affiliation: string,
  classification: string,
  riskScore: number
): ShipEntity {
  return {
    id: mmsi,
    type: "ship",
    mmsi,
    name: shipName,
    shipName,
    lat,
    lon,
    speedKn,
    courseDeg,
    headingDeg,
    shipType,
    affiliation,
    classification,
    riskScore,
    updatedAt: new Date(),
  };
}

