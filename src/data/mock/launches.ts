import type { LaunchEntity } from "./types";

function makeLaunch(
  id: string,
  name: string,
  rocket: string,
  mission: string,
  provider: string,
  padName: string,
  padLat: number,
  padLon: number,
  windowStart: Date,
  windowEnd: Date,
  status: string,
  classification: string,
  riskScore: number
): LaunchEntity {
  return {
    id,
    type: "launch",
    name,
    rocket,
    mission,
    provider,
    padName,
    lat: padLat,
    lon: padLon,
    windowStart,
    windowEnd,
    status,
    classification,
    riskScore,
    updatedAt: new Date(),
  };
}

